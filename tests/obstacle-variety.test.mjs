import assert from 'node:assert/strict';
import {mechanismPose,touchesMechanism,stepDynamicPlayer,createMechanismState,resetMechanismState} from '../dist/mechanisms.js';
import {makeRoute,serializeRoute,validateRoute} from '../dist/segments.js';
import {occupancy,key} from '../dist/world.js';
const dt=1/90,noBlocks=()=>false;
const player=(x=.5,y=1,z=.5)=>({x,y,z,vx:0,vy:0,vz:0,grounded:true,supportId:null});
const tile={id:'tile',type:'collapse',x:0,y:1,z:0,delay:.68,segment:0};
const state=createMechanismState(),p=player(0,1,0);
assert(mechanismPose(tile,0,state).active);
stepDynamicPlayer(p,dt,{move:{x:0,z:0}},noBlocks,[tile],0,state);
assert(state.collapse.has(tile.id));
const warning=mechanismPose(tile,.4,state);assert(warning.warning&&warning.progress>0&&warning.progress<1&&warning.active);
for(let i=1;i<90;i++)stepDynamicPlayer(p,dt,{move:{x:0,z:0}},noBlocks,[tile],i*dt,state);
assert(!mechanismPose(tile,1,state).active);assert(p.y<.7);assert.equal(p.supportId,null);
assert(mechanismPose(tile,100,null).active,'Build preview must leave collapsing tiles intact');
state.collapse.set('other',.1);resetMechanismState(state,[tile,{id:'other',segment:1}],0);
assert(!state.collapse.has('tile')&&state.collapse.has('other'));
assert(mechanismPose(tile,100,state).active);assert.equal(mechanismPose(tile,100,state).y,1);
resetMechanismState(state,[tile]);assert.equal(state.collapse.size,0);
const airborne=player(0,3,0);airborne.grounded=false;
stepDynamicPlayer(airborne,dt,{move:{x:0,z:0}},noBlocks,[tile],0,state);assert.equal(state.collapse.size,0,'Flying over a tile must not trigger it');
const bridge=makeRoute(['collapse']),blocks=occupancy(bridge),solid=(x,y,z)=>blocks.has(key(x,y,z));
const runtime=createMechanismState(),runner=player(bridge.spawn.x,bridge.spawn.y,bridge.spawn.z);
for(let i=0;i<700&&runner.x<bridge.goal.x-.2;i++){
  assert.equal(stepDynamicPlayer(runner,dt,{move:{x:1,z:0}},solid,bridge.mechanisms,i*dt,runtime),null);
  assert(runner.y>.9,'Continuously running must cross the collapsing bridge');
}
assert(runner.x>=bridge.goal.x-.3);assert.equal(runtime.collapse.size,5);
const first=bridge.mechanisms[0],stopped=player(first.x,first.y,first.z),stopState=createMechanismState();
for(let i=0;i<110;i++)stepDynamicPlayer(stopped,dt,{move:{x:0,z:0}},solid,bridge.mechanisms,i*dt,stopState);
assert(stopped.y<.7,'Stopping on a collapsing board must lose support');
const pendulum={id:'pendulum',type:'pendulum',x:3.5,y:11,z:.5,length:9.2,amplitude:.64,period:4.2,phase:0};
assert(touchesMechanism(player(3.5,1,.5),mechanismPose(pendulum,0)));
assert(!touchesMechanism(player(3.5,1,.5),mechanismPose(pendulum,1.05)));
assert(touchesMechanism(player(3.5,1,.5),mechanismPose(pendulum,2.1)));
const floor=(x,y,z)=>y===0&&x>=-5&&x<12&&z>=-5&&z<6;
let walker=player(),hit=null;
for(let i=0;i<100&&!hit;i++)hit=stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[pendulum],1.45+i*dt);
assert.equal(hit?.type,'pendulum');
walker=player();for(let i=0;i<100;i++)assert.equal(stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[pendulum],.4+i*dt),null);
assert(walker.x>4.8,'The pendulum must have a safe crossing window');
const spike={id:'spike',type:'spikes',x:3.5,y:1,z:.5,period:0,phase:0};
assert(touchesMechanism(player(3.5,1,.5),mechanismPose(spike,0)));
assert(!touchesMechanism(player(3.5,1.8,.5),mechanismPose(spike,0)));
walker=player();hit=null;for(let i=0;i<90&&!hit;i++)hit=stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[spike],i*dt);
assert.equal(hit?.type,'spikes');
walker=player();let jumped=false;for(let i=0;i<110;i++){const jump=!jumped&&walker.x>1.4;if(jump)jumped=true;assert.equal(stepDynamicPlayer(walker,dt,{move:{x:1,z:0},jump},floor,[spike],i*dt),null);}
assert(walker.x>5);
const timed={...spike,period:3.2};assert(mechanismPose(timed,.5).active);assert(!mechanismPose(timed,2).active);
walker=player();for(let i=0;i<100;i++)assert.equal(stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[timed],1.5+i*dt),null);
assert(walker.x>4.8);
assert.deepEqual(validateRoute(serializeRoute(bridge)),bridge,'Transient collapse state must never corrupt the saved route');
console.log('Passed: step-triggered warning/collapse, restored retry, continuous-running solution, airborne non-trigger, pendulum hit and timing window, permanent/timed spikes and successful jump.');
