import assert from 'node:assert/strict';
import {mechanismPose,touchesMechanism,stepDynamicPlayer,reachedCheckpoint} from '../dist/mechanisms.js';
import {makeRoute,serializeRoute,validateRoute} from '../dist/segments.js';
import {key,occupancy} from '../dist/world.js';
const dt=1/90;
const deck={id:'deck',type:'platform',x:0,y:1,z:0,dir:1,range:6,lift:2,period:6.4,phase:0};
const gate={id:'gate',type:'gate',x:4,y:1,z:.5,period:4.8,phase:0};
const beam={id:'beam',type:'sweeper',x:3.5,y:1.55,z:.5,speed:0,phase:Math.PI/2};
const noBlocks=()=>false;
const floor=(x,y,z)=>y===0&&x>=-5&&x<12&&z>=-5&&z<6;
const player=(x=.5,y=1,z=.5)=>({x,y,z,vx:0,vy:0,vz:0,grounded:true,supportId:null});
assert.equal(mechanismPose(deck,0).x,0);
assert.equal(mechanismPose(deck,deck.period/2).x,6);
assert.equal(mechanismPose(deck,deck.period/2).y,3);
assert(Math.abs(mechanismPose(deck,deck.period).x)<1e-8);
let rider={...player(0,1,0),supportId:deck.id};
for(let i=0;i<288;i++)stepDynamicPlayer(rider,dt,{move:{x:0,z:0}},noBlocks,[deck],i*dt);
assert(Math.abs(rider.x-6)<.001);assert(Math.abs(rider.y-3)<.001);assert.equal(rider.supportId,deck.id);
const descending={...deck,id:'down',dir:-1,y:10,lift:-2};let down={...player(0,10,0),supportId:'down'};for(let i=0;i<288;i++)stepDynamicPlayer(down,dt,{move:{x:0,z:0}},noBlocks,[descending],i*dt);assert(Math.abs(down.x+6)<.001&&Math.abs(down.y-8)<.001);
let jumper={...player(3,2,0),supportId:deck.id};
stepDynamicPlayer(jumper,dt,{move:{x:0,z:0},jump:true},noBlocks,[deck],1.6);
assert.equal(jumper.supportId,null);assert(jumper.vy>0);
const jumpedX=jumper.x;
for(let i=1;i<15;i++)stepDynamicPlayer(jumper,dt,{move:{x:0,z:0}},noBlocks,[deck],1.6+i*dt);
assert(Math.abs(jumper.x-jumpedX)<.001,'Airborne character must not continue riding the deck');
let lander=player(3,3.2,0);lander.grounded=false;
for(let i=0;i<60;i++)stepDynamicPlayer(lander,dt,{move:{x:0,z:0}},noBlocks,[deck],1.6+i*dt);
assert.equal(lander.supportId,deck.id,'Falling character must be caught by the moving deck');
let off={...player(0,1,0),supportId:deck.id};
for(let i=0;i<100;i++)stepDynamicPlayer(off,dt,{move:{x:0,z:1}},noBlocks,[deck],i*dt);
assert.equal(off.supportId,null);assert(off.y<1);
assert(touchesMechanism(player(4,1,.5),mechanismPose(gate,0)));
assert(!touchesMechanism(player(4,1,.5),mechanismPose(gate,3)));
assert(touchesMechanism(player(4,1,.5),mechanismPose(gate,4.25)));
let walker=player();let hit=null;
for(let i=0;i<90&&!hit;i++)hit=stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[gate],i*dt);
assert.equal(hit?.type,'gate','Closed gate must stop an untimed traversal');
walker=player();for(let i=0;i<90;i++)assert.equal(stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[gate],2.5+i*dt),null);
assert(walker.x>4.8,'Green-light window must permit traversal');
assert(touchesMechanism(player(3.5,1,.5),mechanismPose(beam,0)));
assert(!touchesMechanism(player(3.5,1.8,.5),mechanismPose(beam,0)),'Jump must clear a low sweeper');
walker=player();hit=null;for(let i=0;i<90&&!hit;i++)hit=stepDynamicPlayer(walker,dt,{move:{x:1,z:0}},floor,[beam],i*dt);
assert.equal(hit?.type,'sweeper');
walker=player();let sentJump=false;
for(let i=0;i<110;i++){const jump=!sentJump&&walker.x>1.4;if(jump)sentJump=true;assert.equal(stepDynamicPlayer(walker,dt,{move:{x:1,z:0},jump},floor,[beam],i*dt),null);}
assert(walker.x>5,'A timed jump must cross the sweeper');
const course=makeRoute(['moving']),worldBlocks=occupancy(course),m=course.mechanisms[0];
rider={...player(m.x,m.y,m.z),supportId:m.id};
for(let i=0;i<288;i++)stepDynamicPlayer(rider,dt,{move:{x:0,z:0}},(x,y,z)=>worldBlocks.has(key(x,y,z)),[m],i*dt);
let ticks=288;
for(;ticks<500&&rider.x<course.goal.x-.2;ticks++){stepDynamicPlayer(rider,dt,{move:{x:1,z:0},jump:ticks===288},(x,y,z)=>worldBlocks.has(key(x,y,z)),[m],ticks*dt);assert(rider.y>1.5);}
assert(rider.x>=course.goal.x-.3,'Rider must be able to exit onto the far dock');
const w=makeRoute(['arches','gate','sweeper','moving']);assert.deepEqual(validateRoute(serializeRoute(w)),w);
const cp=w.segments[2].entry;assert.equal(reachedCheckpoint(w.segments,player(cp[0]+.5,cp[1]+1.01,cp[2]+.5),0),2);
assert.equal(reachedCheckpoint(w.segments,player(100,1,100),0),0);
console.log('Passed: timed gate windows and contact, sweeper collision and successful jump, platform boarding/carry/lift/release/jump/landing/far-dock exit, and segment checkpoints.');
